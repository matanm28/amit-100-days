export function getDayFact(daysRemaining: number | null): string | null {
  if (daysRemaining === null || daysRemaining < 1 || daysRemaining > 100) return null;
  return specialDayFacts[daysRemaining] ?? everydayFacts[daysRemaining % everydayFacts.length];
}
